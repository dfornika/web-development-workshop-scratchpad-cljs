#!/bin/bash
set -euo pipefail

npm install

# Pre-fetch the Clojure deps (including the :dev and :test aliases) so the
# first REPL jack-in doesn't have to download shadow-cljs and friends.
clojure -P -M:dev:test

# In GitHub Codespaces, the page served on port 8000 can't reach the
# shadow-cljs websocket at <host>:9630, so point the client at the forwarded
# 9630 URL instead. This goes in the per-user shadow-cljs config, which
# shadow-cljs deep-merges into shadow-cljs.edn, so the project file stays
# untouched. Outside Codespaces we leave the defaults alone.
if [ -n "${CODESPACE_NAME:-}" ]; then
  domain="${GITHUB_CODESPACES_PORT_FORWARDING_DOMAIN:-app.github.dev}"
  devtools_url="https://${CODESPACE_NAME}-9630.${domain}"
  mkdir -p "${HOME}/.shadow-cljs"
  cat > "${HOME}/.shadow-cljs/config.edn" <<EOF
;; Generated by scripts/post-create.sh for this codespace.
{:builds {:app {:devtools {:devtools-url "${devtools_url}"}}}}
EOF
  echo "Configured shadow-cljs devtools-url: ${devtools_url}"
fi
